global.window = {};
require(require('path').join(__dirname, '..', 'js', 'data-ca-2026-general.js'));
const E = window.ELECTION;
let n = 0;
const out = [];
const c = (label, text) => { n++; out.push(`${n}. **${label}:** ${text}`); };
out.push(`# Ballot Swipe fact-check list: ${E.name}`, '');
out.push('Every factual claim shown in the app, numbered so reviewers can reference them ("claim 47 is wrong because...").', '');
out.push('## How to use this with Perplexity', '');
out.push('Paste ONE proposition at a time (not the whole list) with this prompt:', '');
out.push('> I am fact-checking a nonpartisan voter guide for California\'s November 3, 2026 election. For each numbered claim below, tell me: (1) ACCURATE, INACCURATE, or CAN\'T VERIFY; (2) the correct information if it is wrong; (3) the source, preferring the Official Voter Information Guide (voterguide.sos.ca.gov), the Legislative Analyst\'s Office (lao.ca.gov), and Cal-Access/Secretary of State campaign finance data. Also flag any wording that sounds like it favors the YES or NO side.', '');
out.push('Then open the source Perplexity cites and confirm it yourself. AI fact-checkers also make things up, so a claim is verified only when a person has seen it in the primary source.', '');
for (const p of E.props) {
  out.push('', '---', '', `## Prop ${p.num}: ${p.nickname}`, '');
  out.push(`Sources to check against: ${p.sources.map(s => `[${s.label}](${s.url})`).join(' · ')}`, '');
  c('Official title', p.title);
  c('Placed on ballot by', p.placedBy);
  c('In normal human English', p.eli5);
  c('A YES vote means', p.yesMeans);
  c('A NO vote means', p.noMeans);
  c('Supporters say', p.yesSays);
  c('Opponents say', p.noSays);
  p.plain.forEach((t, i) => c(`What it does (${i + 1})`, t));
  c('Cost to the state', p.fiscal);
  c('Named supporters', p.supporters.join('; '));
  c('Named opponents', p.opponents.join('; '));
  const m = p.money || {};
  c('Money, YES side', m.yes || '(not yet filled in: find in SoS contribution tracker)');
  c('Money, NO side', m.no || '(not yet filled in: find in SoS contribution tracker)');
  if (p.conflictNote) c('Conflict note', p.conflictNote);
  out.push('', 'Verified by: ________  Date: ________');
}
out.push('', '---', '', '## Claims on the cheat sheet screen (apply to every user)', '');
c('Election Day', 'Tuesday, November 3, 2026. Polls open 7 a.m. to 8 p.m.');
c('Mail ballots', 'Must be postmarked by Election Day.');
c('Registration', 'Online registration deadline is October 19, 2026. After that, voters can register and vote the same day at their county elections office or a vote center.');
c('Notes in the booth', 'California voters can bring notes or their sample ballot into the voting booth.');
c('Prop numbering', 'Props 1–5 were placed by the Legislature; Props 37–45 by citizen signature petition.');
console.log(out.join('\n'));
